if not SpinArena.Locale then
    SpinArena.Locale = 'fr'
end

if type(SpinArena.L) ~= 'function' then
    function SpinArena.L(key, args, ...)
        local lang = SpinArena.Locale or 'en'
        local dict = (SpinArena.Locales and SpinArena.Locales[lang]) or EN
        local tpl = dict[key] or tostring(key)
        if type(args) == 'table' then
            return (tpl:gsub('{([%w_]+)}', function(k)
                local v = args[k]
                return v ~= nil and tostring(v) or ('{' .. k .. '}')
            end))
        end
        return tpl
    end
end

return EN
